import express from 'express';
import {PGlite} from '@electric-sql/pglite';
import {readFileSync} from 'node:fs';
import {networkInterfaces} from 'node:os';
import {randomBytes} from 'node:crypto';
import {previewAddress} from './preview-config.mjs';
import {ChatStore} from './store.mjs';
import {defaults} from './core.mjs';
import {createChatRouter} from './http.mjs';
const db=new PGlite();
await db.exec(readFileSync(new URL('./schema.sql',import.meta.url),'utf8'));
const store=new ChatStore(db),shop='v0j63n-ms.myshopify.com';
await store.save(shop,{...defaults,enabled:true,aiEnabled:false,faqs:defaults.faqs.map(f=>({...f,approved:true}))},0);
const lan=process.argv.includes('--lan');
const {host,port,origin}=previewAddress({lan,interfaces:lan?networkInterfaces():{},port:process.env.PORT || (lan?4319:4317)});
const app=express();
app.use('/assistant',createChatRouter({env:{NODE_ENV:'development',SHOPIFY_APP_URL:origin,ELUNORA_CHAT_ENABLED:'true',ELUNORA_CHAT_SESSION_SECRET:randomBytes(32).toString('hex')},storeFactory:()=>store,previewOrigin:lan?origin:undefined}));
app.get('/',(req,res)=>res.type('html').send('<!doctype html><html lang="en"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Atelier assistant preview</title><body style="margin:0;background:#eee7dd;font:14px system-ui"><p style="text-align:center">Sample preview · no AI calls · use test details only · inquiries disappear when stopped</p><iframe style="display:block;margin:auto;width:min(100%,440px);height:820px;border:1px solid #cfc5b8;border-radius:12px" title="Atelier assistant" src="/assistant/'+shop+'"></iframe></body></html>'));
app.listen(port,host,()=>{console.info(`Assistant preview: ${origin}`);if(lan)console.info('Open this address on your phone while connected to the same Wi-Fi. Keep this Mac awake. Press Ctrl+C to stop.');});
